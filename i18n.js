  function getLocale() {
    try {
      return localStorage.getItem(STORAGE_KEY);
    } catch {
      return null;
    }
  }

  function apply(code) {
    const locale = locales.find((l) => l.code === code) || locales[0];
    document.documentElement.lang = locale.code;
    document.documentElement.dir = locale.dir;

    const table = dict[locale.code] || dict.en;

    document.querySelectorAll('[data-i18n]').forEach((node) => {
      const key = node.getAttribute('data-i18n');
      const value = table[key] ?? dict.en[key];
      if (value != null) node.textContent = value;
    });

    document.querySelectorAll('[data-i18n-attr]').forEach((node) => {
      node
        .getAttribute('data-i18n-attr')
        .split(',')
        .forEach((pair) => {
          const [attr, key] = pair.split(':').map((part) => part.trim());
          const value = table[key] ?? dict.en[key];
          if (value != null) node.setAttribute(attr, value);
        });
    });

    try {
      localStorage.setItem(STORAGE_KEY, locale.code);
    } catch {
      /* localStorage unavailable (private mode / disabled) */
    }

    document.dispatchEvent(new CustomEvent('memrya:locale-changed', { detail: { locale: locale.code } }));
  }

  function init() {
    let saved = null;
    try {
      saved = localStorage.getItem(STORAGE_KEY);
    } catch {
      /* localStorage unavailable (private mode / disabled) */
    }
    const nav = (navigator.language || 'en').slice(0, 2);
    const requested = new URLSearchParams(window.location.search).get('lang');
    const validRequested = requested && locales.some((l) => l.code === requested)
      ? requested
      : null;
    const initial = validRequested || saved || (locales.some((l) => l.code === nav) ? nav : 'en');
    apply(initial);
  }

  return { dict, locales, apply, getLocale, init };
